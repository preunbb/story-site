#!/usr/bin/env node
/**
 * Scan assets/captions subfolders for final.png and write data/captions.js.
 */
import fs from "fs";
import path from "path";

const ROOT = path.resolve(import.meta.dirname, "..");
const CAPTIONS_ROOT = path.join(ROOT, "assets", "captions");
const OUT_FILE = path.join(ROOT, "data", "captions.js");
const HIDDEN_DIR_PREFIX = "HIDDEN_";

const SECTION_HEADER_RE = /^(left|right|top|bottom)\s*:\s*(.*)$/i;

function parseCaptionSections(content) {
  const sections = {};
  let currentKey = null;
  let currentLines = [];

  const flush = () => {
    if (currentKey != null) {
      sections[currentKey] = currentLines.join("\n").trim();
    }
    currentLines = [];
  };

  for (const line of content.split(/\r?\n/)) {
    const match = line.match(SECTION_HEADER_RE);
    if (match) {
      flush();
      currentKey = match[1].toLowerCase();
      const inline = match[2].trim();
      currentLines = inline ? [inline] : [];
      continue;
    }
    if (currentKey != null) {
      currentLines.push(line);
    }
  }
  flush();
  return sections;
}

function findCaptionTextFile(dir) {
  const captionPath = path.join(dir, "caption.txt");
  if (fs.existsSync(captionPath)) return captionPath;

  const textFiles = fs
    .readdirSync(dir)
    .filter((name) => name.toLowerCase().endsWith(".txt"))
    .map((name) => path.join(dir, name));
  return textFiles.length === 1 ? textFiles[0] : null;
}

function summaryFromSections(sections) {
  const order = ["top", "bottom", "left", "right"];
  return order
    .map((key) => sections[key])
    .filter(Boolean)
    .join(" ")
    .replace(/\s+/g, " ")
    .trim();
}

function humanizeSlug(slug) {
  return slug.replace(/-/g, " ").replace(/\b\w/g, (ch) => ch.toUpperCase());
}

function loadCaptions() {
  if (!fs.existsSync(CAPTIONS_ROOT)) return [];

  const entries = fs
    .readdirSync(CAPTIONS_ROOT, { withFileTypes: true })
    .filter((d) => d.isDirectory())
    .map((d) => d.name)
    .sort((a, b) => a.localeCompare(b));

  const items = [];

  for (const slug of entries) {
    if (slug.startsWith(HIDDEN_DIR_PREFIX)) continue;

    const dir = path.join(CAPTIONS_ROOT, slug);
    const finalPath = path.join(dir, "final.png");
    if (!fs.existsSync(finalPath)) continue;

    const relPath = `assets/captions/${slug}/final.png`;
    let caption = "";
    let alt = humanizeSlug(slug);

    const textFile = findCaptionTextFile(dir);
    if (textFile) {
      const sections = parseCaptionSections(
        fs.readFileSync(textFile, "utf8")
      );
      caption = summaryFromSections(sections);
      if (caption) {
        alt =
          caption.length > 120 ? `${caption.slice(0, 117)}…` : caption;
      }
    }

    items.push({ slug, path: relPath, caption: "", alt });
  }

  return items;
}

function writeCaptionsJs(items) {
  const lines = [
    "// Auto-generated by scripts/sync-captions.mjs — do not edit by hand.",
    "window.DATA_CAPTIONS = [",
  ];

  for (const item of items) {
    lines.push("  {");
    lines.push(`    slug: ${JSON.stringify(item.slug)},`);
    lines.push(`    path: ${JSON.stringify(item.path)},`);
    lines.push(`    caption: ${JSON.stringify(item.caption)},`);
    lines.push(`    alt: ${JSON.stringify(item.alt)},`);
    lines.push("  },");
  }

  lines.push("];");
  lines.push("");
  fs.writeFileSync(OUT_FILE, lines.join("\n"));
}

const items = loadCaptions();
writeCaptionsJs(items);
console.log(`Wrote ${items.length} caption(s) to data/captions.js`);
