#!/usr/bin/env node
/**
 * Scan synced story markdown for [[optional:id|…]] tags and write
 * data/optional-content-index.js (committed; used by Controls on prod).
 */

import { createHash } from "node:crypto";
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { createContext, Script } from "node:vm";

const __dirname = dirname(fileURLToPath(import.meta.url));
const repoRoot = resolve(__dirname, "..");
const STORIES_DIR = join(repoRoot, "assets", "stories");
const OUT = join(repoRoot, "data", "optional-content-index.js");

const OPTIONAL_OPEN_LINE_RE =
  /^\[\[\s*optional\s*:\s*([^\]|]+)(?:\|(.*))?\s*\]\]$/i;

function loadStoryIds() {
  const path = join(repoRoot, "data", "stories.js");
  const src = readFileSync(path, "utf8");
  const ctx = createContext({ window: {} });
  new Script(src).runInContext(ctx);
  const stories = ctx.window.DATA_STORIES || [];
  const byMd = new Map();
  for (const s of stories) {
    if (s && s.id != null && s.driveUrl) {
      byMd.set(String(s.id) + ".md", s.id);
    }
  }
  return byMd;
}

function indexOptionalTags() {
  const byMd = loadStoryIds();
  const byId = new Map();
  if (!existsSync(STORIES_DIR)) {
    return byId;
  }
  for (const file of readdirSync(STORIES_DIR)) {
    if (!file.endsWith(".md") || file.includes("-preview")) continue;
    const storyId = byMd.get(file);
    if (storyId == null) continue;
    const md = readFileSync(join(STORIES_DIR, file), "utf8");
    for (const line of md.split("\n")) {
      const m = line.trim().match(OPTIONAL_OPEN_LINE_RE);
      if (!m) continue;
      const summary = (m[2] || "").trim();
      const ids = m[1]
        .split(",")
        .map((s) => s.trim())
        .filter(Boolean);
      for (const id of ids) {
        let entry = byId.get(id);
        if (!entry) {
          entry = { id, storyIds: new Set(), summaries: [] };
          byId.set(id, entry);
        }
        entry.storyIds.add(storyId);
        if (summary && entry.summaries.indexOf(summary) === -1) {
          entry.summaries.push(summary);
        }
      }
    }
  }
  return byId;
}

function main() {
  const byId = indexOptionalTags();
  const rows = Array.from(byId.values())
    .map((e) => ({
      id: e.id,
      storyIds: Array.from(e.storyIds).sort((a, b) => Number(a) - Number(b)),
      summary: e.summaries[0] || "",
    }))
    .sort((a, b) =>
      a.id.localeCompare(b.id, undefined, { sensitivity: "base" }),
    );

  const body =
    "/** Auto-generated by scripts/index-optional-content.mjs — do not edit. */\n" +
    "window.OPTIONAL_CONTENT_INDEX = " +
    JSON.stringify(rows, null, 2) +
    ";\n";

  const prev = existsSync(OUT) ? readFileSync(OUT, "utf8") : "";
  const hash = createHash("sha256").update(body).digest("hex").slice(0, 8);
  if (prev === body) {
    console.log(`[optional-index] unchanged (${rows.length} types, ${hash})`);
    return;
  }
  writeFileSync(OUT, body, "utf8");
  console.log(
    `[optional-index] wrote ${rows.length} optional content type(s) to data/optional-content-index.js`,
  );
  for (const r of rows) {
    console.log(
      `  · ${JSON.stringify(r.id)} (stories: ${r.storyIds.join(", ")})`,
    );
  }
}

main();